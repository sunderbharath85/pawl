// Copy step: repo-root assets/pets (owned by art-sprites) -> apps/mobile/assets/pets, then generate
// src/generated/pet-sprites.ts with static `require()` calls (Metro can only bundle static requires).
//
// Run: `bun run copy-pets` (also runs before `start`/`ios`/`android`). Safe to re-run; missing sprites are
// fine — the app falls back to the built-in react-native-svg pets.
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { parseSpriteManifest, type SpriteAnimationName, type SpriteManifest } from "@ai-pet/pet-engine";

const appRoot = resolve(import.meta.dir, "..");
const srcDir = resolve(appRoot, "../../assets/pets");
const outDir = join(appRoot, "assets/pets");
const genFile = join(appRoot, "src/generated/pet-sprites.ts");

function copyTree(from: string, to: string): number {
  let n = 0;
  mkdirSync(to, { recursive: true });
  for (const name of readdirSync(from)) {
    const a = join(from, name);
    const b = join(to, name);
    if (statSync(a).isDirectory()) n += copyTree(a, b);
    else if (/\.(png|json)$/i.test(name)) {
      copyFileSync(a, b);
      n++;
    }
  }
  return n;
}

function emit(manifest: SpriteManifest | null): string {
  const lines: string[] = [
    "// GENERATED by scripts/copy-pets.ts from assets/pets/manifest.json. Do not edit by hand.",
    'import type { Species } from "@ai-pet/protocol";',
    'import type { SpriteAnimationName } from "@ai-pet/pet-engine";',
    "",
    "export interface BundledSpriteAnimation {",
    "  /** Metro asset id from a static require(). */",
    "  source: number;",
    "  frames: number;",
    "  fps: number;",
    "  loop: boolean;",
    "}",
    "",
    `export const SPRITE_FRAME_SIZE = ${manifest?.frameSize ?? 256};`,
    "",
    "export const PET_SPRITES: Partial<Record<Species, Partial<Record<SpriteAnimationName, BundledSpriteAnimation>>>> = {",
  ];
  for (const [species, sp] of Object.entries(manifest?.species ?? {})) {
    if (!sp) continue;
    const anims = Object.entries(sp.animations) as [SpriteAnimationName, NonNullable<(typeof sp.animations)[SpriteAnimationName]>][];
    const present = anims.filter(([, a]) => existsSync(join(outDir, a.src)));
    if (present.length === 0) continue;
    lines.push(`  ${JSON.stringify(species)}: {`);
    for (const [name, a] of present) {
      const rel = `../../assets/pets/${a.src.replace(/^\.?\/+/, "")}`;
      lines.push(
        `    ${JSON.stringify(name)}: { source: require(${JSON.stringify(rel)}), frames: ${a.frames}, fps: ${a.fps}, loop: ${a.loop} },`,
      );
    }
    lines.push("  },");
  }
  lines.push("};", "");
  return lines.join("\n");
}

let manifest: SpriteManifest | null = null;
if (existsSync(join(srcDir, "manifest.json"))) {
  rmSync(outDir, { recursive: true, force: true });
  const n = copyTree(srcDir, outDir);
  manifest = parseSpriteManifest(JSON.parse(readFileSync(join(outDir, "manifest.json"), "utf8")));
  console.log(`copy-pets: copied ${n} files to assets/pets${manifest ? "" : " (manifest invalid: SVG fallback only)"}`);
} else {
  console.warn(`copy-pets: ${srcDir} has no manifest.json; keeping existing assets/pets (SVG fallback if empty)`);
  const local = join(outDir, "manifest.json");
  if (existsSync(local)) manifest = parseSpriteManifest(JSON.parse(readFileSync(local, "utf8")));
}

mkdirSync(dirname(genFile), { recursive: true });
writeFileSync(genFile, emit(manifest));
console.log(`copy-pets: wrote ${genFile}`);
